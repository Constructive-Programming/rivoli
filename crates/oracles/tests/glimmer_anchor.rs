//! **The vendored Muse Glimmer S1b anchor goldens must stay loadable, complete, self-describing,
//! and the exact bytes that were measured.**
//!
//! `docs/measurement/glimmer-reference/anchor.md` is the record; `tests/glimmer_anchor_driver.py`
//! produced the files and `tests/glimmer-anchor.sh` reproduces them.
//!
//! **This is a fixture-integrity gate, not a correctness gate for the port**, and that is worth
//! saying plainly: nothing here compares any rivoli output to a golden, because at S1b there is no
//! Glimmer kernel to score — so the literal answer to "what wrong implementation passes this" is
//! every one. What it does is hold the files to the shape S2's kernels will reach for, refuse a
//! file that is not the one the doc describes, and refuse a tiny config that has stopped matching
//! the real checkpoint's structure.
//!
//! **No GPU, no python, no network.** Generating a golden needs a pinned venv; reading one needs
//! nothing, which is why the bytes are vendored. Unlike K3's anchor it does not need a device even
//! to generate — this reference is plain PyTorch — but the vendoring argument is unchanged.
//!
//! **Two salts and two modes are vendored and every test runs over all of them.** One draw cannot
//! show that a property is a fact about the arithmetic rather than about the numbers it landed on.
//!
//! **Each `#[test]` below is a driver over named `check_*` helpers rather than one long body.**
//! That is a code-health requirement, not taste — the CodeScene gate refuses a file with deeply
//! nested test bodies or long unbroken runs of assertions, and a run of asserts with no name on it
//! is exactly the shape that makes a failure read as "something in this file broke".
//!
//! **FOUR binaries over one fixture set, split 2026-08-15 for the 800-line gate.** The split is by
//! what a group asserts about, which is how the file already grouped itself:
//!
//! | binary | holds |
//! |---|---|
//! | this one | what is true of a FILE — provenance, the byte pins, the weight sets, and that the values inside are usable |
//! | `glimmer_anchor_text.rs` | the text goldens' structure: the tiny config, the widths, the layer pattern, the capture census |
//! | `glimmer_anchor_draft.rs` | the shapes that make the DFlash drafter a drafter rather than a small target |
//! | `glimmer_anchor_arithmetic.rs` | the two properties read off the VALUES: the QK-norm's axis, and Q's scale against K's |
//!
//! The tables and the accessors all four read through are `glimmer_anchor_common/mod.rs`.

#![allow(clippy::unwrap_used, clippy::expect_used)] // tests: panic-on-failure is the idiom
#[path = "glimmer_anchor_common/mod.rs"]
mod anchor; // keep this preamble blank-line-free: spread out, these are a jscpd clone
use anchor::golden_read;
use anchor::{GOLDENS, GoldenSet, Vendored, cfg, is_mode, load, meta, num};

/// The weight sets S3 item 3 exports, pinned exactly as the goldens are.
///
/// **A separate table rather than two more `GOLDENS` rows**, because that table means "mode x salt"
/// and three helpers filter it by a name prefix that IS the mode; a `weights-N` row would have to
/// answer `is_mode` and would be dragged into every text test, which expects captures it does not
/// hold. Its metadata says `mode=text` — it inherits the run's — so the name cannot carry the mode
/// here without lying.
///
/// **Why they need pinning at all:** review, 2026-08-13, found them vendored outside every
/// provenance gate the rest of this anchor is built on — no length, no FNV, in no census, and not
/// regenerated by `glimmer-anchor.sh`. The commit that added them verified byte-identity by hand
/// once, and this repo's own lesson is that a pin checked once by hand is decoration.
///
/// > **GREW 18x on 2026-08-13**, from 113,035 B holding `attn.gate_proj` alone to 2,065,185 B
/// > holding the tiny model's WHOLE parameter set — 107 tensors, ~485k floats. The driver's own
/// > docstring had specified this change and its price ("~1.9 MB per salt — a decision to make
/// > deliberately, not by accretion"), and what it buys is the only comparison in this tree that is
/// > against Muse Glimmer rather than against rivoli's reading of it: `tests/glimmer_reference.rs`
/// > builds a checkpoint from these parameters, runs the engine's own loop on it, and scores the
/// > logits against `tN.logits`.
/// >
/// > **The goldens did not move**, which is the property that makes the change additive and which
/// > `glimmer-anchor.sh` re-proves on every run: both were regenerated with the extended dump and
/// > came back byte-identical to the vendored bytes.
const WEIGHT_SETS: &[Vendored] = &[
    Vendored {
        name: "weights-1",
        bytes: include_bytes!("glimmer-anchor-weights-1.bin"),
        len: 2_065_185,
        fnv: 0x8328_514c_9e73_d150,
    },
    Vendored {
        name: "weights-2",
        bytes: include_bytes!("glimmer-anchor-weights-2.bin"),
        len: 2_065_185,
        fnv: 0x4b5d_75e6_0b80_1cc4,
    },
];

