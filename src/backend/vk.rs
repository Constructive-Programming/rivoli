/// Device-to-device copy of `bytes` from `src` to `dst` — the routed arena's slot
/// relocation (compaction). `hip::memcpy_dtod`'s twin, and like it this BLOCKS, so the
/// moved expert is in place before any later kernel reads the new slot.
///
/// # Safety
/// `dst` and `src` must be DEVICE ADDRESSES inside live [`Buf`]s, `bytes` long, and
/// NON-OVERLAPPING (the arena guarantees distinct slots).
pub unsafe fn memcpy_dtod(dst: *mut u8, src: *const u8, bytes: usize) -> Result<()> {
    ensure!(bytes > 0, "memcpy_dtod: argument guard rejected");
    let g = gpu()?;
    let (dbuf, doff) = resolve(dst as u64, bytes)?;
    let (sbuf, soff) = resolve(src as u64, bytes)?;
    let region = [vk::BufferCopy::default()
        .src_offset(soff)
        .dst_offset(doff)
        .size(bytes as u64)];
    g.enqueue(|d, cb| {
        // SAFETY: recording is open; both handles came from `resolve`, so each range
        // lies inside its buffer.
        unsafe { d.cmd_copy_buffer(cb, sbuf, dbuf, &region) };
    })?;
    g.sync()
}

/// ASYNC host-to-device copy on the FETCH queue — `rivoli_memcpy_h2d_async`'s twin, and
/// the third of Phase 4's three violations fixed.
///
/// It RETURNS BEFORE THE BYTES LAND. What says they have landed is the [`Signal`] the
/// caller arms next (`Signal::arm_on(&Stream)` → [`Gpu::arm_on`]), which flushes this
/// recorded copy and fires when that submit retires. That is exactly the HIP contract:
/// `hipMemcpyAsync` on the fetch stream, then a completion signal on the same stream.
///
/// # What this replaces, and why the old version was a violation and not a slow path
///
/// `stream.rs`'s Vulkan `stage::copy_to_slot` was `std::ptr::copy_nonoverlapping`: the
/// REAPER THREAD's CPU copying ~2.16 GB per token, synchronously, with the decode thread
/// free to do nothing about it. A DMA engine does that work here, off both threads, and the
/// reaper returns to the ring immediately — which is the only way the fetch↔compute overlap
/// can exist at all.
///
/// Both ends are HOST pointers, resolved back to their `VkBuffer` by [`resolve_host`]:
/// `src` is a slot in the io_uring bounce arena ([`Buf::staging`]) and `dst` is a slot in
/// the routed pool's mapping (`ArenaPool::host_ptr`). Passing host pointers is not a
/// concession — it is what makes the signature identical on both backends, since under HIP
/// the same number is also the device address.
///
/// The reader's ordering is NOT this function's business, and the split matters: the fetch
/// queue must not overwrite a slot the MoE queue is still reading, and that is the
/// RESIDENCY layer's job — `pin.rs`'s per-batch pin set (`begin_batch` clears it, `protect`
/// pins every hit, `admit` pins every miss) makes a slot touched this batch un-evictable
/// until the batch ends, and the end-of-layer `device_sync` closes the batch. The queue
/// layer owns only the WRITE side of a slot. Two mechanisms both believing they own slot
/// lifetime is how a subtle double-free of *bytes* gets built.
///
/// (docs/VULKAN.md called this "the `inflight` guard". No such guard exists under that name
/// — the mechanism is the per-batch pin set above, and a reader grepping for `inflight`
/// finds nothing. The doc is corrected; this note is here because the wrong name is what is
/// written in the planning text a future porter will read first.)
///
/// # Safety
/// `dst` and `src` must be HOST addresses inside live [`Buf`] mappings, `n` bytes long, and
/// non-overlapping. `dst`'s slot must stay valid until the caller's `Signal` fires — the
/// copy reads `src` and writes `dst` on the GPU timeline, after this returns.
pub unsafe fn copy_h2d_async(dst: *mut u8, src: *const u8, n: usize) -> Result<()> {
    ensure!(n > 0, "copy_h2d_async: zero-length copy");
    let g = gpu()?;
    let (dbuf, doff) = resolve_host(dst, n)?;
    let (sbuf, soff) = resolve_host(src, n)?;
    let region = [vk::BufferCopy::default()
        .src_offset(soff)
        .dst_offset(doff)
        .size(n as u64)];
    g.enqueue_on(Q::Fetch, |d, cb| {
        // SAFETY: recording is open; both handles came from `resolve_host`, so each range
        // lies inside its buffer.
        unsafe { d.cmd_copy_buffer(cb, sbuf, dbuf, &region) };
    })
}

/// Fill `bytes` at `dst` with the 32-bit pattern `pat` (`bytes` a multiple of 4).
/// `hip::fill_u32`'s twin: it poisons a freshly admitted expert slot so a read-before-
/// write is DETERMINISTIC rather than dependent on what was in memory (`pin.rs`, under
/// `trace`).
///
/// `vkCmdFillBuffer` rather than a shader — that command IS this kernel, so
/// `kernels/vmm.hip::fill_u32` has no GLSL twin and never needs one. Unlike
/// [`memcpy_dtod`] this does NOT sync: the fill is recorded into the open command buffer
/// and `enqueue`'s barrier orders it against whatever reads the slot next, which is what
/// the HIP side gets from launching on the null stream.
///
/// # Safety
/// `dst` must be a DEVICE ADDRESS inside a live [`Buf`] owning at least `bytes`.
pub unsafe fn fill_u32(dst: *mut u8, pat: u32, bytes: usize) -> Result<()> {
    ensure!(
        bytes > 0 && bytes.is_multiple_of(4),
        "fill_u32: {bytes} bytes is not a positive multiple of 4"
    );
    let g = gpu()?;
    let (buf, off) = resolve(dst as u64, bytes)?;
    // vkCmdFillBuffer requires a 4-byte-aligned offset AND size. `bytes` is checked
    // above; the offset comes from `resolve`, so it inherits the caller's alignment and
    // has to be checked here rather than assumed.
    ensure!(
        off.is_multiple_of(4),
        "fill_u32 dst {dst:?} is at offset {off} in its buffer, which vkCmdFillBuffer \
         requires to be 4-byte aligned"
    );
    g.enqueue(|d, cb| {
        // SAFETY: recording is open; `buf`/`off` came from `resolve`, so the range lies
        // inside the buffer, and both offset and size are 4-aligned (checked above).
        unsafe { d.cmd_fill_buffer(cb, buf, off, bytes as u64, pat) };
    })
}

/// Declare a `push_constant` mirror struct, with both of its invariants checked AT
/// COMPILE TIME rather than left as rules a porter has to remember at kernel 11 of 16:
///
/// - **No padding.** `dispatch` reads the struct as its own bytes; padding bytes are
///   uninitialised, and reading them as `u8` is UB. std430 would also place the
///   shader's fields differently than a padded Rust struct does, so the values would
///   silently land in the wrong slots. A `u64` after an `i32` introduces four bytes of
///   it, which is one field reorder away at every future launcher.
/// - **Fits the guaranteed budget.** 128 bytes is all Vulkan promises. Exceeding it is
///   the "push-constant budget" risk in docs/VULKAN.md; this makes it a build error
///   instead of a device-dependent surprise, so the params-buffer fallback gets built
///   the day it is actually needed and not before.
///
/// Order fields largest-first (8-byte device addresses, then 4-byte scalars) and the
/// no-padding check is satisfied naturally.
macro_rules! push_struct {
    ($(#[$m:meta])* $name:ident { $($(#[$fm:meta])* $f:ident: $t:ty),+ $(,)? }) => {
        $(#[$m])*
        #[repr(C)]
        struct $name { $($(#[$fm])* $f: $t),+ }
        const _: () = assert!(
            size_of::<$name>() == 0 $(+ size_of::<$t>())+,
            concat!(stringify!($name), " has padding: reorder fields largest-first"),
        );
        const _: () = assert!(
            size_of::<$name>() <= 128,
            concat!(stringify!($name), " exceeds the 128-byte guaranteed push budget"),
        );
    };
}

push_struct! {
    /// Mirror of `gemv_f32.comp`'s `push_constant` block. std430: three 8-byte buffer
    /// references then two ints — 32 bytes.
    GemvF32Push {
        x: u64,
        w: u64,
        y: u64,
        o_dim: i32,
        i_dim: i32,
    }
}

/// Workgroups needed to cover `n` elements at one element per invocation.
fn groups(n: usize) -> u32 {
    n.div_ceil(BLOCK as usize) as u32
}

/// A device address handed to a shader that reads or writes it as 32-bit WORDS must be
/// word-aligned, because the shader's offset arithmetic is relative to this base.
///
/// [`WORD`] and `DeviceTier::place` fix the LENGTH half of the word-addressing hazard;
/// this is the ALIGNMENT half. Every current caller satisfies it — `Buf` bases come
/// from `vkGetBufferDeviceAddress` and `place` results are 256-aligned — but the byte-
/// and u16-typed arguments (`packed`, `lc8`, `rc`) are exactly the shapes a caller
/// could hand a sub-pointer: a per-layer KV slab offset, a compacted arena slot. GPU-AV
/// checks out-of-bounds, not misalignment, so nothing else would catch it.
fn ensure_word_aligned(p: u64, what: &str) -> Result<()> {
    ensure!(
        (p as usize).is_multiple_of(WORD),
        "{what} address {p:#x} is not {WORD}-byte aligned — the shader reads it as \
         32-bit words, and its offsets are relative to this base"
    );
    Ok(())
}

/// f32 GEMV `y = W·x` (the MoE router gate).
///
/// # Safety
/// `x`, `w` and `y` must be DEVICE ADDRESSES of live [`Buf`] regions holding `i_dim`,
/// `o_dim·i_dim` and `o_dim` f32 respectively, and must stay live until the next
/// [`device_sync`].
#[allow(clippy::too_many_arguments)]
pub unsafe fn launch_gemv_f32(
    x: *const f32,
    w: *const f32,
    o_dim: usize,
    i_dim: usize,
    nrow: usize,
    y: *mut f32,
) -> Result<()> {
    ensure!(o_dim > 0 && i_dim > 0, "gemv_f32: argument guard rejected");
    ensure!(
        nrow == 1,
        "gemv_f32: nrow={nrow} — batched token rows are not implemented on Vulkan \
         (the .comp shaders are single-row); use --features rocm"
    );
    let g = gpu()?;
    let push = GemvF32Push {
        x: x as u64,
        w: w as u64,
        y: y as u64,
        o_dim: o_dim as i32,
        i_dim: i_dim as i32,
    };
    g.dispatch(
        &g.pipes.gemv_f32,
        &push,
        o_dim.div_ceil(ROWS_PER_BLOCK as usize) as u32,
    )
}

