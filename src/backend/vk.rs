/// One device allocation: a `VkBuffer` bound to its own `VkDeviceMemory`, permanently
/// host-mapped, exposed to the kernels by its DEVICE ADDRESS.
///
/// This is the primitive `device.rs`'s `DeviceBuf`/`DeviceTier`/`VmmBuf` are built
/// from. On Strix Halo host RAM *is* GPU memory, so the same allocation is both
/// device-local (full bandwidth) and host-writable in place — the Vulkan spelling of
/// what `kernels/vmm.hip` does with HIP VMM.
pub struct Buf {
    buf: vk::Buffer,
    mem: vk::DeviceMemory,
    addr: u64,
    host: *mut u8,
    len: usize,
}

// SAFETY: `Buf` is `!Send` only because of the `host` raw pointer, which is a permanent
// `vkMapMemory` result owned solely by this `Buf`. Moving that ownership to another thread
// is sound: `VkDevice` is internally synchronised, the map lives until `Drop` (which itself
// only calls `Gpu::sync`, and `Gpu` is `Send + Sync`), and every host access goes through
// `&self`/`&mut self` methods, so Rust's own aliasing rules still decide who may touch the
// mapping. NOT `Sync`, and deliberately: nothing here needs a shared `&Buf` across threads,
// and `read_into` reading a mapping a kernel may be writing is a contract question rather
// than one the compiler can settle.
//
// Needed by `stream.rs`'s staging-arena registry, which owns the bounce arena's `Buf` in a
// static while `Streamer` (on the reaper thread) holds its host pointer.
unsafe impl Send for Buf {}

/// Every live [`Buf`], so a device address can be mapped back to the `VkBuffer` that
/// owns it.
///
/// This is the lookup table docs/VULKAN.md rejects for the launcher path — and the
/// reasoning still holds there. It is acceptable HERE because `vkCmdCopyBuffer` takes
/// handles and offsets and there is no copy-by-address command.
///
/// # It now has a decode-path caller, and that is a considered reversal
///
/// The rule used to be "do not let it grow a second caller on the decode path", written
/// when the only caller was arena compaction (occasional, synchronous, already moving whole
/// expert blocks). Phase 4's async staging copy ([`copy_h2d_async`]) breaks it: one lookup
/// per cold expert, so a few hundred per token. The alternative was threading `VkBuffer`
/// handles up through `stream.rs`'s `ReadSpec` and `pin.rs`'s pool — into code shared with
/// the HIP backend, which has no such concept because a HIP device pointer resolves to its
/// allocation inside the driver. Doing the same resolution here, in the same place, next to
/// a 20 MB DMA, is the smaller price: a linear scan of a few dozen entries is tens of
/// nanoseconds against a copy measured in hundreds of microseconds.
///
/// What has NOT changed is the rule for the LAUNCHERS: they still pass bare device
/// addresses and must never consult this.
static ALLOCS: Mutex<Vec<Alloc>> = Mutex::new(Vec::new());

struct Alloc {
    base: u64,
    len: u64,
    buf: vk::Buffer,
    /// The owning `Buf`'s HOST mapping base, so a device address can be turned back into a
    /// readable host address. Only [`read_raw`] uses it — see the note there.
    host: *mut u8,
}

// SAFETY: `host` is a permanent `vkMapMemory` result for an allocation that outlives every
// registry entry (deregistration happens in `Buf::drop` BEFORE the unmap). The registry only
// ever hands it out under its own mutex, and `read_raw` — its sole reader — copies out of it
// after a `device_sync`. The pointer is not dereferenced by the registry itself.
unsafe impl Send for Alloc {}

/// Look up `[addr, addr+len)` in the registry and project one field out of the owning
/// allocation. Shared by [`resolve`] and [`read_raw`] so the bounds and overflow checks
/// exist once — they were duplicated, and the second copy is exactly where an off-by-one
/// would live unnoticed.
fn lookup<T>(addr: u64, len: usize, f: impl Fn(&Alloc, u64) -> T) -> Result<T> {
    let allocs = ALLOCS.lock().map_err(|_| anyhow!("vk alloc registry poisoned"))?;
    let end = addr
        .checked_add(len as u64)
        .ok_or_else(|| anyhow!("device address {addr:#x} + {len} overflows"))?;
    allocs
        .iter()
        .find(|a| addr >= a.base && end <= a.base + a.len)
        .map(|a| f(a, addr - a.base))
        .ok_or_else(|| {
            anyhow!("device address {addr:#x}..{end:#x} is not inside any live Buf")
        })
}

/// The `VkBuffer` owning `[addr, addr+len)`, and the offset into it.
fn resolve(addr: u64, len: usize) -> Result<(vk::Buffer, u64)> {
    lookup(addr, len, |a, off| (a.buf, off))
}

/// As [`resolve`], but keyed on the HOST mapping instead of the device address.
///
/// The fetch path needs this and cannot use `resolve`: `pin.rs` hands the streamer
/// `ArenaPool::host_ptr` — the io_uring DMA target — because that is the pointer an
/// O_DIRECT read and a CPU memcpy both need, and under HIP it is *also* the device address
/// so one number served both. Here they are unrelated, so a copy expressed in host
/// pointers has to be translated back. Same bounds and overflow checks, one predicate
/// apart; deliberately NOT folded into `lookup` with a flag, because the two key spaces
/// must never be confused and a boolean parameter is exactly how they would be.
fn resolve_host(host: *const u8, len: usize) -> Result<(vk::Buffer, u64)> {
    let allocs = ALLOCS.lock().map_err(|_| anyhow!("vk alloc registry poisoned"))?;
    let base = host as usize;
    let end = base
        .checked_add(len)
        .ok_or_else(|| anyhow!("host address {base:#x} + {len} overflows"))?;
    allocs
        .iter()
        .find(|a| base >= a.host as usize && end <= a.host as usize + a.len as usize)
        .map(|a| (a.buf, (base - a.host as usize) as u64))
        .ok_or_else(|| {
            anyhow!("host address {base:#x}..{end:#x} is not inside any live Buf's mapping")
        })
}

/// DIAGNOSTIC: read `len` bytes back from an arbitrary DEVICE ADDRESS into `out`.
///
/// The Vulkan twin of `hip.rs`'s `DeviceBuf::copy_out_raw`, and the second caller of the
/// address registry `Buf`'s own comment warned not to grow. It earns the exception on the
/// same terms `memcpy_dtod` does and one more:
///
/// - It is `trace`-only. Its sole caller is the expert-checksum / NaN-localizer probe, so it
///   is never on the decode path and a linear scan of a handful of entries costs nothing.
/// - There is no alternative. A bare device address carries no object identity, which is the
///   whole reason `device.rs` deferred this — but the alternative to building it is that
///   `--features vulkan,trace` does not COMPILE, and a feature combination that cannot be
///   built is worse than a lookup nobody times.
///
/// Reads the host mapping directly, so unlike `hipMemcpy` it does NOT synchronise.
///
/// # Safety
/// `src` must be a device address inside a live [`Buf`], readable for `len` bytes, and no
/// kernel may be concurrently writing them — call after a [`device_sync`].
pub unsafe fn read_raw(src: *const u8, len: usize, out: &mut Vec<u8>) -> Result<()> {
    ensure!(len > 0, "read_raw: zero-length read");
    let host = lookup(src as u64, len, |a, off| {
        // SAFETY: `off + len <= a.len` was checked by `lookup`, and the mapping covers the
        // whole allocation.
        unsafe { a.host.add(off as usize) }
    })?;
    out.clear();
    out.reserve(len);
    // SAFETY: `host` is readable for `len` (bounds-checked above); `out` owns `len` reserved
    // bytes; the two are distinct allocations.
    unsafe {
        std::ptr::copy_nonoverlapping(host, out.as_mut_ptr(), len);
        out.set_len(len);
    }
    Ok(())
}

impl Buf {
    /// # MEASURED: an allocation above ~4 GiB exceeds `maxMemoryAllocationSize` here.
    ///
    /// The first Vulkan run against the real artifact allocated the 16.16 GiB resident tier
    /// and the 43.8 GiB routed pool as ONE `Buf` each, and the validation layer flagged both:
    ///
    /// ```text
    /// vkAllocateMemory(): pAllocateInfo->allocationSize (47070568448) is larger than
    /// maxMemoryAllocationSize (4294967292)
    /// ```
    ///
    /// It WORKED — the driver honoured both and the token decoded — but that is the layer's
    /// point: the limit is advertised, this exceeds it by 11x, and the spec permits
    /// `VK_ERROR_OUT_OF_DEVICE_MEMORY` instead. Not fixed here because fixing it means
    /// suballocating `DeviceTier`/`VmmBuf` across several allocations, which changes the
    /// address arithmetic `pin.rs`'s arena is built on. Recorded so the next reader knows it
    /// is KNOWN rather than unnoticed.
    ///
    /// Two consequences that bite before the fix lands:
    ///
    /// - **Any test that allocates more than 4 GiB will fail `Validation::check`**, which
    ///   asserts zero validation messages. Every current test is far below it.
    /// - **A Vulkan build logs two validation ERRORs during pin construction.** They are not
    ///   spurious and must not be filtered out — see `debug_callback`'s note on what does
    ///   and does not get counted.
    pub fn new(len: usize) -> Result<Self> {
        Self::alloc(len, false)
    }

    /// A HOST-MEMORY buffer for the io_uring bounce arena: `HOST_VISIBLE | HOST_COHERENT`
    /// and, where the device offers the choice, **NOT `DEVICE_LOCAL`**.
    ///
    /// That exclusion is the whole reason this constructor exists, and it is a correctness
    /// property rather than a preference. The bounce arena is the destination of an
    /// O_DIRECT io_uring read, so the kernel has to `get_user_pages` it — which is exactly
    /// what amdgpu refused for device-local VMM pages (`stream.rs`'s header: EFAULT on
    /// 6.18.38-and-earlier, the bug bounce mode exists to work around). Allocating the
    /// bounce arena out of device-local memory would reintroduce that failure on the very
    /// path built to avoid it. It also keeps the ~40% system-vs-device read tax on the
    /// GPU's side of the copy rather than the NVMe's.
    ///
    /// Falls back to any `HOST_VISIBLE | HOST_COHERENT` type if the device has nothing
    /// non-device-local, and says so — on a unified-memory part that fallback may be the
    /// only option, and refusing to run would be worse than a warning.
    pub fn staging(len: usize) -> Result<Self> {
        Self::alloc(len, true)
    }

    fn alloc(len: usize, host_only: bool) -> Result<Self> {
        ensure!(len > 0, "Buf::new(0): Vulkan rejects a zero-sized buffer");
        let g = gpu()?;
        // Allocate word-rounded (see [`WORD`]) but keep `self.len` at the REQUESTED
        // size. That asymmetry is the whole safety property and it is easy to "tidy"
        // away: storing `alloc` instead would silently widen `write_at`/`read_into`'s
        // bounds checks by up to three bytes, converting a fix for an accidental
        // overrun into a licence for deliberate ones. The padding exists so a shader's
        // 32-bit read of the FINAL byte stays inside the buffer — nothing else may see
        // it, and no caller may write into it.
        //
        // Free: Vulkan's memory requirements are granular far above 4 bytes, so this
        // rounds into padding the allocator was going to add anyway.
        let alloc = len.next_multiple_of(WORD);
        let bci = vk::BufferCreateInfo::default()
            .size(alloc as u64)
            .usage(
                vk::BufferUsageFlags::STORAGE_BUFFER
                    | vk::BufferUsageFlags::SHADER_DEVICE_ADDRESS
                    | vk::BufferUsageFlags::TRANSFER_SRC
                    | vk::BufferUsageFlags::TRANSFER_DST,
            )
            .sharing_mode(vk::SharingMode::EXCLUSIVE);
        // SAFETY: the device is live; `bci` outlives the call.
        let buf = unsafe { g.device.create_buffer(&bci, None) }?;
        // Allocation failure is RECOVERABLE here — the engine hits it during weight
        // residency and reports it — so every `?` below must undo what came before.
        // Leaking a VkBuffer per attempt would exhaust handles across a retry while
        // still reporting OOM, which reads as the wrong bug.
        match Self::finish(g, buf, len, host_only) {
            Ok(b) => Ok(b),
            Err(e) => {
                // SAFETY: `buf` is live, unbound, and referenced by nothing.
                unsafe { g.device.destroy_buffer(buf, None) };
                Err(e)
            }
        }
    }

    fn finish(
        g: &'static Gpu,
        buf: vk::Buffer,
        len: usize,
        host_only: bool,
    ) -> Result<Self> {
        // SAFETY: `buf` was just created on this device.
        let req = unsafe { g.device.get_buffer_memory_requirements(buf) };
        let hostbits =
            vk::MemoryPropertyFlags::HOST_VISIBLE | vk::MemoryPropertyFlags::HOST_COHERENT;
        let want = if host_only {
            hostbits
        } else {
            hostbits | vk::MemoryPropertyFlags::DEVICE_LOCAL
        };
        let types = &g.memprops.memory_types[..g.memprops.memory_type_count as usize];
        let fits = |i: usize, t: &vk::MemoryType, avoid_local: bool| {
            req.memory_type_bits & (1 << i) != 0
                && t.property_flags.contains(want)
                && !(avoid_local
                    && t.property_flags
                        .contains(vk::MemoryPropertyFlags::DEVICE_LOCAL))
        };
        // Staging asks for non-device-local FIRST and settles for device-local only if the
        // device has nothing else. `new` (host_only == false) is unaffected: it asks for
        // DEVICE_LOCAL, so the first pass and the fallback are the same predicate and it
        // picks the same type it always did.
        let idx = types
            .iter()
            .enumerate()
            .position(|(i, t)| fits(i, t, host_only))
            .or_else(|| {
                if host_only {
                    warn!(
                        "no non-DEVICE_LOCAL HOST_VISIBLE|HOST_COHERENT memory type: the \
                         io_uring bounce arena will live in device-local memory, which is \
                         the configuration amdgpu once EFAULTed on (see stream.rs)"
                    );
                }
                types
                    .iter()
                    .enumerate()
                    .position(|(i, t)| fits(i, t, false))
            })
            .ok_or_else(|| {
                // HOST_COHERENT is not a convenience here. Without it, host writes are
                // not visible to the device until vkFlushMappedMemoryRanges, and the
                // failure mode is STALE DATA READ AS VALID — no fault, no validation
                // message, wrong numbers. Refusing to allocate is the only safe
                // response short of implementing the flush, and a driver that forces
                // that choice should say so at startup rather than at token 300.
                anyhow!(
                    "no {want:?} memory type for a {len} B buffer. Without HOST_COHERENT \
                     every in-place host fill needs an explicit vkFlushMappedMemoryRanges, \
                     which this backend does not do."
                )
            })? as u32;
        let mut flags =
            vk::MemoryAllocateFlagsInfo::default().flags(vk::MemoryAllocateFlags::DEVICE_ADDRESS);
        let ai = vk::MemoryAllocateInfo::default()
            .allocation_size(req.size)
            .memory_type_index(idx)
            .push_next(&mut flags);
        // SAFETY: as above.
        let mem = unsafe { g.device.allocate_memory(&ai, None) }?;
        let bind_and_map = || -> Result<*mut u8> {
            // SAFETY: `mem` was allocated for `buf`'s requirements, nothing is bound
            // yet, and the mapping covers the whole allocation.
            unsafe {
                g.device.bind_buffer_memory(buf, mem, 0)?;
                Ok(g.device
                    .map_memory(mem, 0, req.size, vk::MemoryMapFlags::empty())?
                    as *mut u8)
            }
        };
        let host = match bind_and_map() {
            Ok(h) => h,
            Err(e) => {
                // SAFETY: `mem` is live and (on the bind-failure path) unbound; the
                // caller destroys `buf`.
                unsafe { g.device.free_memory(mem, None) };
                return Err(e);
            }
        };
        let info = vk::BufferDeviceAddressInfo::default().buffer(buf);
        // SAFETY: `buf` was created with SHADER_DEVICE_ADDRESS and is bound.
        let addr = unsafe { g.device.get_buffer_device_address(&info) };
        // Registering is the LAST fallible step, and it comes after `mem` is allocated
        // and mapped — so its error path has to undo those, not just let `Buf::new`
        // destroy the buffer. Every other `?` in this function has a matching undo and
        // this one did not, which contradicted the comment two screens up saying they
        // all do.
        match ALLOCS.lock() {
            Ok(mut allocs) => allocs.push(Alloc {
                base: addr,
                len: len as u64,
                buf,
                host,
            }),
            Err(_) => {
                // SAFETY: `mem` is bound and mapped, owned solely by this half-built
                // Buf; the caller destroys `buf`.
                unsafe {
                    g.device.unmap_memory(mem);
                    g.device.free_memory(mem, None);
                }
                bail!("vk alloc registry poisoned");
            }
        }
        Ok(Self {
            buf,
            mem,
            addr,
            host,
            len,
        })
    }

    /// The buffer's DEVICE address, shaped as a pointer so the `launch_*` signatures
    /// match `hip.rs`'s exactly.
    ///
    /// **Not dereferenceable on the host.** Under HIP unified addressing the host and
    /// device see one address; under Vulkan they do not. Host access goes through
    /// [`Buf::write_at`] / [`Buf::read_into`], and the engine only ever passes these
    /// values through to kernels — which is why the swap costs `gpu.rs` nothing.
    pub fn ptr(&self) -> *const u8 {
        self.addr as *const u8
    }
    pub fn ptr_mut(&mut self) -> *mut u8 {
        self.addr as *mut u8
    }

    /// The HOST base of the permanent mapping — a real, dereferenceable pointer, and
    /// the target an io_uring O_DIRECT read DMAs into.
    ///
    /// This is the OTHER half of the pair [`ptr`](Self::ptr) documents: under HIP these
    /// are one number and `VmmBuf::ptr_mut` serves both purposes, which is why
    /// `pin.rs`'s `ArenaPool` can use one base for descriptor arithmetic and for
    /// `ReadSpec.dst`. Here they are unrelated, so the caller has to say which one it
    /// means. See docs/VULKAN.md, "Host pointer != device address".
    pub fn host_mut(&mut self) -> *mut u8 {
        self.host
    }

    /// Host-write `bytes` at byte offset `off`. HOST_COHERENT, and `vkQueueSubmit`
    /// implies the host-write barrier, so no flush and no `hipMemcpy` — the write is
    /// visible to any kernel submitted after it returns.
    pub fn write_at(&mut self, off: usize, bytes: &[u8]) -> Result<()> {
        // checked_add, not `off + len`: this is a SAFE fn, and in release `off` near
        // usize::MAX would wrap the sum to something small, pass the check, and let
        // copy_nonoverlapping write outside the mapping.
        ensure!(
            off.checked_add(bytes.len()).is_some_and(|e| e <= self.len),
            "write_at {off}+{} > buf len {}",
            bytes.len(),
            self.len
        );
        // SAFETY: the mapping covers `self.len`; `off+len` is within it (checked).
        unsafe { std::ptr::copy_nonoverlapping(bytes.as_ptr(), self.host.add(off), bytes.len()) };
        Ok(())
    }

    /// Read the first `len` bytes back into `out` (cleared, then refilled). Call after
    /// a [`device_sync`] — that is where the kernels' writes are made host-visible.
    pub fn read_into(&self, out: &mut Vec<u8>, len: usize) -> Result<()> {
        ensure!(len <= self.len, "read_into {len} > buf len {}", self.len);
        out.clear();
        out.reserve(len);
        // SAFETY: the mapping covers `self.len >= len`; `out` owns `len` reserved bytes.
        unsafe {
            std::ptr::copy_nonoverlapping(self.host, out.as_mut_ptr(), len);
            out.set_len(len);
        }
        Ok(())
    }
}

impl Drop for Buf {
    fn drop(&mut self) {
        let Ok(g) = gpu() else { return };
        // Flush first. Every buffer reaches the shader as a bare device address baked
        // into a push constant at RECORD time, so a dispatch recorded before this drop
        // still references these bytes — and because the address carries no object
        // identity, not even a validation layer could catch the use-after-free. A no-op
        // when nothing is recorded, which is the common case.
        if let Err(e) = g.sync() {
            warn!("Buf::drop: flush failed, freeing anyway: {e:#}");
        }
        // Deregister BEFORE the handles die, so `resolve` can never hand a freed
        // VkBuffer to vkCmdCopyBuffer. If the registry is unreachable we LEAK rather
        // than free: a stale entry pointing at a destroyed buffer is a use-after-free
        // with no object identity for any layer to catch, which is strictly worse than
        // an allocation that outlives its owner.
        match ALLOCS.lock() {
            Ok(mut allocs) => allocs.retain(|a| a.base != self.addr),
            Err(_) => {
                error!(
                    "vk alloc registry poisoned; LEAKING buffer at {:#x} rather than \
                     leaving a stale entry that resolve() could hand to a copy",
                    self.addr
                );
                return;
            }
        }
        // SAFETY: all three handles came from this device and are released once. The
        // caller's contract (see `device_sync`) is that no kernel still references them.
        unsafe {
            g.device.unmap_memory(self.mem);
            g.device.destroy_buffer(self.buf, None);
            g.device.free_memory(self.mem, None);
        }
    }
}

