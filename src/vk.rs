const VALIDATION_LAYER: &CStr = c"VK_LAYER_KHRONOS_validation";

/// Alignment an `O_DIRECT` read requires of its destination buffer. The cold-expert
/// streamer DMAs straight into a [`Buf`]'s host mapping, so a mapping that is not this
/// aligned makes every read fail `EINVAL` — deep inside the reaper, on some future
/// machine, long after startup. See [`Buf::host_mut`].
pub const O_DIRECT_ALIGN: usize = 4096;

/// Shaders read packed `u8`/`u16` weights as 32-bit WORDS — `VK_KHR_8bit_storage` is
/// deliberately not required (docs/VULKAN.md) — so the word holding the LAST byte of an
/// unaligned buffer extends up to 3 bytes past it. Every allocation is rounded up to
/// this so that read stays in bounds.
///
/// Found by GPU-assisted validation, not by an oracle: `embed_i8_row` over a
/// 5 x 37 = 185-byte table had invocation 36 read the word at offset 184, three bytes
/// past the end. Every numeric test PASSED — in the default config and under
/// synchronisation validation — because the out-of-range bytes land in the discarded
/// lanes of the word. GPU-AV was the only thing that could see it.
pub const WORD: usize = 4;

// `WAVE` and `ROWS_PER_BLOCK`, generated by build.rs from the same constants it
// passes to glslc with -D. Declaring them here as well and hoping the two stay equal
// is what HIP avoids by deriving ROW_GRID/ROW_BLOCK from one common.hpp define: a
// mismatch dispatches too few workgroups and the unwritten output rows keep their old
// contents — no fault, and no validation diagnostic either.
//
// WAVE is 32 because gfx1151 is native wave32; the pipelines pin it with
// `requiredSubgroupSize` + REQUIRE_FULL_SUBGROUPS, so a driver that cannot honour it
// fails at init rather than silently reducing gl_NumSubgroups (which would leave the
// upper rows of every workgroup unwritten — see gemv_f32.comp).
include!(concat!(env!("OUT_DIR"), "/dims.rs"));

/// Threads per workgroup. The shaders' `local_size_x`.
pub const BLOCK: u32 = ROWS_PER_BLOCK * WAVE;

/// Instance, device, the dedicated compute queue, and a command pool on it. Built
/// once by [`gpu`]; never dropped (see the note there).
pub struct Gpu {
    pub device: ash::Device,
    pub memprops: vk::PhysicalDeviceMemoryProperties,
    instance: ash::Instance,
    phys: vk::PhysicalDevice,
    /// Owns the dlopen'd libvulkan; must outlive the instance, never called through.
    _entry: ash::Entry,
    cmd: Mutex<Cmd>,
    pipes: Pipes,
    validation: bool,
    budget: bool,
    timeline: Timeline,
    /// Did the waiter thread actually start? `gpu()` publishes the context BEFORE
    /// spawning, so a spawn failure (EAGAIN under thread pressure) returns Err from
    /// the first call while every later call short-circuits on the published value and
    /// returns Ok. Without this flag the process would then run with no waiter: every
    /// `signal()` would submit happily and no Signal would ever resolve, presenting as
    /// a hang in the async path long after the transient failure that caused it.
    waiter: AtomicBool,
}

/// Count of validation ERROR/WARNING messages seen. Tests assert it is zero, so a
/// layer diagnostic FAILS THE RUN instead of scrolling past in a log nobody reads.
pub static VALIDATION_ERRORS: std::sync::atomic::AtomicUsize =
    std::sync::atomic::AtomicUsize::new(0);

unsafe extern "system" fn debug_callback(
    sev: vk::DebugUtilsMessageSeverityFlagsEXT,
    ty: vk::DebugUtilsMessageTypeFlagsEXT,
    data: *const vk::DebugUtilsMessengerCallbackDataEXT<'_>,
    _user: *mut std::ffi::c_void,
) -> vk::Bool32 {
    // SAFETY: the loader guarantees `data` points at a valid struct for this call.
    let msg = unsafe { (*data).message_as_c_str() }
        .unwrap_or(c"<no message>")
        .to_string_lossy()
        .into_owned();
    let err = sev.contains(vk::DebugUtilsMessageSeverityFlagsEXT::ERROR);
    // SAFETY: the loader guarantees `data` points at a valid struct for this call.
    let id = unsafe { (*data).message_id_name_as_c_str() }
        .unwrap_or(c"")
        .to_string_lossy()
        .into_owned();
    // Two classes are logged but NOT counted, because counting them would make the
    // assertion fire on something that is not a finding — and an assertion that cries
    // wolf gets deleted rather than triaged.
    //
    //   PERFORMANCE — advice, not misuse ("your dispatch is small").
    //   The layer talking ABOUT ITSELF — enabling GPU-AV makes it emit
    //   VALIDATION-SETTINGS ("GPU-AV and core both on is slow") and
    //   WARNING-Setting-Limit-Adjusted ("forcing vulkanMemoryModel to TRUE so I can
    //   instrument your shaders"). Those describe the checker's configuration, not our
    //   Vulkan usage, and without this the suite can NEVER pass under GPU-AV — which
    //   is the one checker that covers the bare-device-address design.
    //
    // Matched by exact message-ID name, not a substring of the body: narrow enough
    // that a real finding cannot hide behind it.
    let self_report = matches!(
        id.as_str(),
        "VALIDATION-SETTINGS" | "WARNING-Setting-Limit-Adjusted"
    );
    if !ty.contains(vk::DebugUtilsMessageTypeFlagsEXT::PERFORMANCE) && !self_report {
        VALIDATION_ERRORS.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
    }
    // stderr UNCONDITIONALLY, in addition to `tracing`.
    //
    // Not belt-and-braces: `tracing` alone is a NULL SINK in the binary that matters.
    // The test harness installs no subscriber, so the counter above would move while
    // the message text vanished — a validation failure would report as a bare number
    // with no way to learn what the layer said, and the counter moving would make the
    // messenger look like it worked. The alternative fix (install a subscriber in the
    // test binary) leaves the same hole for anything else that links this crate
    // without one. eprintln has no such dependency.
    let level = if err { "ERROR" } else { "WARNING" };
    eprintln!("vk validation {level}: {msg}");
    if err {
        tracing::error!("vk validation: {msg}");
    } else {
        warn!("vk validation: {msg}");
    }
    vk::FALSE
}

/// The one open command buffer every `launch_*` appends to, plus the fence
/// [`device_sync`] joins on. Mirrors HIP's default stream: launches queue up, the
/// sync submits and waits. One buffer, reset and refilled — no per-launch submit
/// (colibri measured submit cost as the thing that matters on RADV).
struct Cmd {
    /// The queue lives HERE, not on `Gpu`, and that placement is load-bearing.
    ///
    /// `vkQueueSubmit` requires the VkQueue to be externally synchronised. When the
    /// handle sat beside the mutex instead of inside it, "always submit under the
    /// guard" was a convention — and `Gpu::signal` broke it within a day of the rule
    /// being written down, while carrying a SAFETY comment citing the very invariant it
    /// violated. Inside the guard, submitting without the lock is a borrow error rather
    /// than something a reader has to notice.
    queue: vk::Queue,
    pool: vk::CommandPool,
    buf: vk::CommandBuffer,
    fence: vk::Fence,
    recording: bool,
    /// Buffers a launcher had to allocate to carry data the push constant cannot hold —
    /// today only `rope`'s host-computed trig table. They must outlive RECORDING (a
    /// dispatch reads them) but not the sync, so they are dropped after the fence.
    ///
    /// Dropped OUTSIDE the mutex, in `sync`: `Buf::drop` calls `Gpu::sync`, which takes
    /// this same non-reentrant lock. Freeing them while holding it deadlocks.
    scratch: Vec<Buf>,
    /// Set by any failure in [`Gpu::sync`]. Each of its fallible calls leaves the
    /// buffer in a DIFFERENT illegal state — invalid after a failed `end`, executable
    /// after a failed submit, *pending* after a failed fence wait — and the pool has
    /// no `RESET_COMMAND_BUFFER` bit, so `vkBeginCommandBuffer` is only legal from the
    /// initial state. Since `device_sync` returns a `Result` the engine can observe
    /// the error and carry on, which would put every later submit into undefined
    /// behaviour, silently, with no validation layer to say so. So the failure is
    /// STICKY: once poisoned, nothing is recorded or submitted again.
    poisoned: bool,
}

/// A compiled compute kernel. Every pipeline here has an EMPTY descriptor-set layout:
/// buffers reach the shader as device addresses in push constants, which is HIP's raw
/// pointer args translated literally (docs/VULKAN.md, "kernel raw pointer args").
struct Pipe {
    layout: vk::PipelineLayout,
    pipe: vk::Pipeline,
    /// Bytes the layout declares. `dispatch` asserts the push struct matches: pushing
    /// more than the range is a VUID violation with nothing else to catch it.
    push_size: u32,
}

/// Every kernel, compiled once at init. Grows one field per ported kernel.
struct Pipes {
    gemv_f32: Pipe,
    embed_i8_row: Pipe,
    append_kv: Pipe,
    gather_rope: Pipe,
    vadd: Pipe,
    flag_nonfinite: Pipe,
    argmax_reduce: Pipe,
    swiglu: Pipe,
    rmsnorm: Pipe,
    rope_interleave: Pipe,
    gemv_i8: Pipe,
    gemv_fp8: Pipe,
    mla_value_fp8: Pipe,
    mla_absorb_fp8: Pipe,
    mla_latent_attend: Pipe,
    mla_attend_combine: Pipe,
    moe_gateup_vq: Pipe,
    moe_down_vq: Pipe,
    moe_reduce: Pipe,
}

// SAFETY: needed because ash models the DISPATCHABLE handles (`vk::Queue`,
// `vk::CommandBuffer`) as raw pointers, hence `!Send`/`!Sync`; the non-dispatchable
// ones are `u64` and already fine.
//
// The invariant is ENFORCED, not asserted. Everything Vulkan requires to be externally
// synchronised — the queue, the command pool, the command buffer — is a field of the
// private `Cmd` struct behind `self.cmd`, so reaching any of them requires the mutex
// guard and there is no discipline to remember. `device` is public, but `VkDevice` is
// internally synchronised.
//
// This comment used to describe a convention instead, and `Gpu::signal` violated it
// while citing it. If a future change moves a synchronised handle back out of `Cmd`,
// this paragraph becomes false again — keep them inside.
unsafe impl Send for Gpu {}
unsafe impl Sync for Gpu {}

static GPU: OnceLock<Gpu> = OnceLock::new();

/// The process-global context, built on first use.
///
/// Not dropped: it lives until exit, and tearing a Vulkan device down while the
/// engine's buffers (also static-lifetime, also never freed on the HIP side) still
/// hold handles would be strictly worse than letting the OS reclaim it.
pub fn gpu() -> Result<&'static Gpu> {
    // Double-checked: the fast path is a plain atomic load, and the slow path is
    // taken once per process. `OnceLock::get_or_init` alone would be wrong here —
    // `Gpu::new` is fallible, so init has to happen outside the closure, and two
    // threads racing would each build a whole VkInstance + VkDevice + pipeline set
    // with the loser's LEAKED (Gpu has no Drop, deliberately). The decode loop is
    // single-threaded so this never fires in the engine, but cargo's test harness
    // runs tests in parallel threads and every one of them calls `gpu()`.
    //
    // No deadlock surface: nothing reachable from `Gpu::new` calls `gpu()`.
    if let Some(g) = GPU.get() {
        return Ok(g);
    }
    static INIT: Mutex<()> = Mutex::new(());
    let _lk = INIT.lock().map_err(|_| anyhow!("vk init lock poisoned"))?;
    if let Some(g) = GPU.get() {
        return Ok(g);
    }
    let g = Gpu::new()?;
    let g = GPU.get_or_init(|| g);
    // Spawned here, not in `Gpu::new`: the waiter needs a `&'static Gpu`, which only
    // exists once the OnceLock owns it. Runs for the life of the process; `Gpu` is
    // never dropped, so there is nothing for it to outlive.
    std::thread::Builder::new()
        .name("rivoli-vk-timeline".into())
        .spawn(move || timeline_waiter(g))?;
    g.waiter.store(true, Ordering::Release);
    Ok(g)
}

impl Gpu {
    fn new() -> Result<Self> {
        // SAFETY: loads libvulkan; the returned Entry owns it for the process.
        let entry = unsafe { ash::Entry::load() }
            .map_err(|e| anyhow::anyhow!("no Vulkan loader: {e}"))?;

        let app = vk::ApplicationInfo::default()
            .application_name(c"rivoli")
            .api_version(vk::API_VERSION_1_3);
        let validation = Self::validation_layer(&entry);
        let all = [VALIDATION_LAYER.as_ptr()];
        // VK_EXT_debug_utils is what carries the layer's diagnostics to us. Without a
        // messenger, "validation ENABLED" would mean the layer talks to a settings
        // file and nothing else — reaching neither `tracing` nor a test assertion,
        // which is the same "green run mistaken for a validated one" the layer is
        // supposed to prevent. The extension is provided by the loader independently
        // of the layer, so we ask for it whenever it is advertised.
        let debug = Self::has_extension(&entry, ash::ext::debug_utils::NAME);
        let exts = [ash::ext::debug_utils::NAME.as_ptr()];
        let ci = vk::InstanceCreateInfo::default()
            .application_info(&app)
            .enabled_layer_names(&all[..validation as usize])
            .enabled_extension_names(&exts[..debug as usize]);
        // SAFETY: `ci` and everything it borrows outlive the call.
        let instance = unsafe { entry.create_instance(&ci, None) }?;
        if debug {
            Self::attach_messenger(&entry, &instance)?;
        }

        let (phys, qfam) = Self::pick(&instance)?;
        // NOTE: the queue handle is deliberately NOT fetched here. It belongs to `Cmd`,
        // behind the mutex, so that submitting without the guard cannot compile.
        // Live free-memory reporting; see `mem_info`. Optional because the fallback
        // (free == total) is merely useless, not wrong.
        let budget = Self::has_device_extension(&instance, phys, ash::ext::memory_budget::NAME);
        let device = Self::create_device(&instance, phys, qfam, budget)?;
        // SAFETY: `phys` is a live physical device from this instance.
        let memprops = unsafe { instance.get_physical_device_memory_properties(phys) };
        let cmd = Cmd::new(&device, qfam)?;
        let pipes = Pipes::new(&device)?;
        let timeline = Timeline::new(&device)?;

        Ok(Self {
            device,
            memprops,
            instance,
            phys,
            _entry: entry,
            cmd: Mutex::new(cmd),
            pipes,
            validation,
            budget,
            timeline,
            waiter: AtomicBool::new(false),
        })
    }

    /// Is `VK_LAYER_KHRONOS_validation` installed? Says so either way, at WARN when
    /// it is not — same rule as `device.rs`'s sole-tenant guard: a silently-inert
    /// safety net is worse than none, because you believe you are protected.
    ///
    /// This backend passes every buffer as a raw device address with no descriptor
    /// sets, and a bad address or a missing barrier reads plausible GARBAGE rather
    /// than faulting. The validation layer is the only thing that catches that class;
    /// `spirv-val` (run by build.rs) checks module wellformedness, not API use.
    fn validation_layer(entry: &ash::Entry) -> bool {
        // SAFETY: the loader is live.
        let Ok(layers) = (unsafe { entry.enumerate_instance_layer_properties() }) else {
            warn!("VULKAN VALIDATION OFF: could not enumerate instance layers");
            return false;
        };
        let found = layers.iter().any(|l| {
            l.layer_name_as_c_str()
                .is_ok_and(|n| n == VALIDATION_LAYER)
        });
        if found {
            info!("Vulkan validation layer ENABLED");
        } else {
            warn!(
                "VULKAN VALIDATION OFF: {} not installed. Buffer-device-address and \
                 synchronisation misuse will read garbage instead of failing.",
                VALIDATION_LAYER.to_string_lossy()
            );
        }
        found
    }

    fn has_extension(entry: &ash::Entry, name: &CStr) -> bool {
        // SAFETY: the loader is live.
        unsafe { entry.enumerate_instance_extension_properties(None) }
            .is_ok_and(|xs| xs.iter().any(|x| x.extension_name_as_c_str() == Ok(name)))
    }

    /// Route the validation layer's ERROR/WARNING messages into `tracing` and count
    /// them, so a diagnostic can FAIL A TEST rather than scroll past. Without this the
    /// layer's output goes wherever its settings file says, which is nowhere useful.
    fn attach_messenger(entry: &ash::Entry, instance: &ash::Instance) -> Result<()> {
        use vk::DebugUtilsMessageSeverityFlagsEXT as Sev;
        use vk::DebugUtilsMessageTypeFlagsEXT as Ty;
        let ci = vk::DebugUtilsMessengerCreateInfoEXT::default()
            .message_severity(Sev::ERROR | Sev::WARNING)
            .message_type(Ty::GENERAL | Ty::VALIDATION | Ty::PERFORMANCE)
            .pfn_user_callback(Some(debug_callback));
        let dbg = ash::ext::debug_utils::Instance::new(entry, instance);
        // SAFETY: `instance` is live and `ci` outlives the call. The messenger is
        // never destroyed — it must outlive every other object, and the instance is
        // itself never destroyed (see `gpu`).
        unsafe { dbg.create_debug_utils_messenger(&ci, None) }?;
        Ok(())
    }

    /// Whether this context is running under the validation layer. Tests print it so
    /// a green run is never mistaken for a validated one.
    pub fn validation(&self) -> bool {
        self.validation
    }

    /// First physical device whose queue families and features satisfy the whole
    /// contract. If none does, report EVERY missing item for the *last* candidate
    /// rather than a bare "no suitable device" — on a one-GPU box that is the answer.
    fn pick(instance: &ash::Instance) -> Result<(vk::PhysicalDevice, u32)> {
        // SAFETY: `instance` is live.
        let devices = unsafe { instance.enumerate_physical_devices() }?;
        let mut last: Option<(String, Vec<String>)> = None;
        for phys in devices {
            // SAFETY: `phys` came from this instance.
            let props = unsafe { instance.get_physical_device_properties(phys) };
            let name = props.device_name_as_c_str().map_or_else(
                |_| "<unnamed>".to_string(),
                |s| s.to_string_lossy().into_owned(),
            );
            let mut missing = Vec::new();
            if props.api_version < vk::API_VERSION_1_3 {
                missing.push(format!(
                    "Vulkan 1.3 (device reports {}.{})",
                    vk::api_version_major(props.api_version),
                    vk::api_version_minor(props.api_version)
                ));
            }
            let qfam = Self::compute_queue(instance, phys);
            if qfam.is_none() {
                missing.push("a COMPUTE queue family".into());
            }
            missing.extend(Self::missing_features(instance, phys));
            match (qfam, missing.is_empty()) {
                (Some(q), true) => return Ok((phys, q)),
                _ => last = Some((name, missing)),
            }
        }
        match last {
            Some((name, missing)) => bail!(
                "no Vulkan device meets the rivoli contract; closest was {name}, missing: {}",
                missing.join(", ")
            ),
            None => bail!("no Vulkan physical devices found"),
        }
    }

    /// A DEDICATED compute family (COMPUTE without GRAPHICS) if the device has one,
    /// else any COMPUTE family. Colibri measured the dedicated queue as the better
    /// choice on RADV (commit 4d4cacc) — it does not contend with the compositor.
    fn compute_queue(instance: &ash::Instance, phys: vk::PhysicalDevice) -> Option<u32> {
        // SAFETY: `phys` came from `instance`.
        let fams = unsafe { instance.get_physical_device_queue_family_properties(phys) };
        let compute =
            |f: &vk::QueueFamilyProperties| f.queue_flags.contains(vk::QueueFlags::COMPUTE);
        fams.iter()
            .position(|f| compute(f) && !f.queue_flags.contains(vk::QueueFlags::GRAPHICS))
            .or_else(|| fams.iter().position(compute))
            .map(|i| i as u32)
    }

    /// Every required feature the device lacks, named as the spec names it so the
    /// failure is actionable. Fail fast beats a mystery `VK_ERROR_DEVICE_LOST` later.
    fn missing_features(instance: &ash::Instance, phys: vk::PhysicalDevice) -> Vec<String> {
        let mut v11 = vk::PhysicalDeviceVulkan11Features::default();
        let mut v12 = vk::PhysicalDeviceVulkan12Features::default();
        let mut v13 = vk::PhysicalDeviceVulkan13Features::default();
        // Scoped so the pNext chain's mutable borrows end and the filled-in structs
        // can be read below.
        let core = {
            let mut f2 = vk::PhysicalDeviceFeatures2::default()
                .push_next(&mut v11)
                .push_next(&mut v12)
                .push_next(&mut v13);
            // SAFETY: `phys` is live; the chain is valid for the duration of the call.
            unsafe { instance.get_physical_device_features2(phys, &mut f2) };
            f2.features
        };

        let mut sub = vk::PhysicalDeviceSubgroupProperties::default();
        let mut size = vk::PhysicalDeviceSubgroupSizeControlProperties::default();
        let p2 = {
            let mut p2 = vk::PhysicalDeviceProperties2::default()
                .push_next(&mut sub)
                .push_next(&mut size);
            // SAFETY: as above.
            unsafe { instance.get_physical_device_properties2(phys, &mut p2) };
            vk::PhysicalDeviceProperties2 {
                properties: p2.properties,
                ..Default::default()
            }
        };

        let mut missing = Vec::new();
        let mut need = |ok: bool, what: &str| {
            if !ok {
                missing.push(what.to_string());
            }
        };
        // Lets ExpertDesc's six raw pointers stay six uint64 addresses in a push
        // constant instead of six descriptor bindings rewritten per expert.
        need(v12.buffer_device_address == vk::TRUE, "bufferDeviceAddress");
        // ...which the shader dereferences as uint64_t buffer references.
        need(core.shader_int64 == vk::TRUE, "shaderInt64");
        need(v12.timeline_semaphore == vk::TRUE, "timelineSemaphore");
        // The fp16 VQ codebook.
        need(v12.shader_float16 == vk::TRUE, "shaderFloat16");
        need(v11.storage_buffer16_bit_access == vk::TRUE, "storageBuffer16BitAccess");
        // WAVE 32 is not negotiable — the reductions are a fixed 32-lane ladder.
        need(v13.subgroup_size_control == vk::TRUE, "subgroupSizeControl");
        need(v13.compute_full_subgroups == vk::TRUE, "computeFullSubgroups");
        need(
            size.min_subgroup_size <= WAVE && WAVE <= size.max_subgroup_size,
            &format!(
                "a subgroup size of {WAVE} (device allows {}..={})",
                size.min_subgroup_size, size.max_subgroup_size
            ),
        );
        need(
            size.required_subgroup_size_stages.contains(vk::ShaderStageFlags::COMPUTE),
            "requiredSubgroupSizeStages including COMPUTE",
        );
        need(
            sub.supported_stages.contains(vk::ShaderStageFlags::COMPUTE),
            "subgroup operations in COMPUTE",
        );
        // The shaders declare local_size_x = BLOCK. Vulkan only GUARANTEES 128
        // invocations and (128,128,64), both below the 256 we need, so a conformant
        // minimum-limits device would fail vkCreateComputePipelines with an opaque
        // ERROR_INITIALIZATION_FAILED instead of naming the limit. gfx1151 allows
        // 1024; the point of this function is the machines that are not gfx1151.
        let lim = p2.properties.limits;
        need(
            lim.max_compute_work_group_invocations >= BLOCK,
            &format!(
                "maxComputeWorkGroupInvocations >= {BLOCK} (device allows {})",
                lim.max_compute_work_group_invocations
            ),
        );
        need(
            lim.max_compute_work_group_size[0] >= BLOCK,
            &format!(
                "maxComputeWorkGroupSize[0] >= {BLOCK} (device allows {})",
                lim.max_compute_work_group_size[0]
            ),
        );
        // VUID-VkPipelineShaderStageCreateInfo-pNext-02759: local_size_x must fit in
        // maxComputeWorkgroupSubgroups * requiredSubgroupSize.
        need(
            size.max_compute_workgroup_subgroups >= ROWS_PER_BLOCK,
            &format!(
                "maxComputeWorkgroupSubgroups >= {ROWS_PER_BLOCK} (device allows {})",
                size.max_compute_workgroup_subgroups
            ),
        );
        // `supported_operations` is a free bitmask and only BASIC is mandatory, so each
        // op family a shader uses must be named. BALLOT arrived with 2c: `subgroupBroadcast`
        // in mla_latent_attend compiles to OpGroupNonUniformBroadcast, which the spec puts
        // behind the BALLOT bit rather than BASIC. Without this line a device advertising
        // BASIC|SHUFFLE_RELATIVE but not BALLOT passes init cleanly and then fails at
        // pipeline creation with an opaque ERROR_INITIALIZATION_FAILED naming nothing.
        for (flag, name) in [
            (vk::SubgroupFeatureFlags::BASIC, "subgroup BASIC"),
            (vk::SubgroupFeatureFlags::SHUFFLE_RELATIVE, "subgroup SHUFFLE_RELATIVE"),
            (vk::SubgroupFeatureFlags::BALLOT, "subgroup BALLOT (subgroupBroadcast)"),
        ] {
            need(sub.supported_operations.contains(flag), name);
        }
        // The attention tile is a STATIC shared array — GLSL has no dynamic LDS — and at
        // 16*(512+64) f32 it is 36864 bytes. That is over Vulkan's REQUIRED minimum for
        // maxComputeSharedMemorySize, which is 16384, so it is a real portability limit
        // rather than a formality: every earlier shader here fits in ~1-2 KB. The shader
        // comment used to claim this was checked at init; now it is.
        need(
            lim.max_compute_shared_memory_size >= MLA_ATTEND_LDS_BYTES,
            &format!(
                "maxComputeSharedMemorySize >= {MLA_ATTEND_LDS_BYTES} for the attention tile \
                 (device allows {})",
                lim.max_compute_shared_memory_size
            ),
        );
        // On Strix Halo host RAM *is* GPU memory (GTT); the pin path writes resident
        // weights straight into device-local memory, so this heap must exist.
        // SAFETY: `phys` is live.
        let mp = unsafe { instance.get_physical_device_memory_properties(phys) };
        let want = vk::MemoryPropertyFlags::DEVICE_LOCAL | vk::MemoryPropertyFlags::HOST_VISIBLE;
        need(
            mp.memory_types[..mp.memory_type_count as usize]
                .iter()
                .any(|t| t.property_flags.contains(want)),
            "a DEVICE_LOCAL | HOST_VISIBLE memory type",
        );
        missing
    }

    fn has_device_extension(
        instance: &ash::Instance,
        phys: vk::PhysicalDevice,
        name: &CStr,
    ) -> bool {
        // SAFETY: `phys` came from `instance`.
        unsafe { instance.enumerate_device_extension_properties(phys) }
            .is_ok_and(|xs| xs.iter().any(|x| x.extension_name_as_c_str() == Ok(name)))
    }

    fn create_device(
        instance: &ash::Instance,
        phys: vk::PhysicalDevice,
        qfam: u32,
        budget: bool,
    ) -> Result<ash::Device> {
        let prio = [1.0f32];
        let qci = [vk::DeviceQueueCreateInfo::default()
            .queue_family_index(qfam)
            .queue_priorities(&prio)];
        let mut v11 = vk::PhysicalDeviceVulkan11Features::default().storage_buffer16_bit_access(true);
        let mut v12 = vk::PhysicalDeviceVulkan12Features::default()
            .buffer_device_address(true)
            .timeline_semaphore(true)
            .shader_float16(true);
        let mut v13 = vk::PhysicalDeviceVulkan13Features::default()
            .subgroup_size_control(true)
            .compute_full_subgroups(true);
        let core = vk::PhysicalDeviceFeatures::default().shader_int64(true);
        // Every REQUIRED extension is core in 1.3 — including subgroup_size_control
        // and buffer_device_address. memory_budget is the one optional extra.
        let exts = [ash::ext::memory_budget::NAME.as_ptr()];
        let ci = vk::DeviceCreateInfo::default()
            .queue_create_infos(&qci)
            .enabled_extension_names(&exts[..budget as usize])
            .enabled_features(&core)
            .push_next(&mut v11)
            .push_next(&mut v12)
            .push_next(&mut v13);
        // SAFETY: `phys` is live and `ci` outlives the call; features were verified
        // present by `missing_features` before we got here.
        Ok(unsafe { instance.create_device(phys, &ci, None) }?)
    }

    /// Free device memory and total, in bytes — `hipMemGetInfo`'s twin.
    ///
    /// `free` is LIVE, via VK_EXT_memory_budget: `DeviceTier::new` gates the tier on
    /// `capacity + 4 GiB headroom <= free`, and substituting the heap SIZE there would
    /// admit a tier that cannot actually fit alongside the compositor and the driver's
    /// own allocations. The failure would then surface as an OOM part-way through
    /// weight loading instead of a clean refusal at startup, which is precisely what
    /// the headroom rule and the sole-tenant guard exist to prevent.
    ///
    /// Falls back to `free == total` only if the extension is absent — and says so,
    /// because a budget guard silently comparing against the heap size is a guard that
    /// always passes.
    pub fn mem_info(&self) -> (usize, usize) {
        let heaps = &self.memprops.memory_heaps[..self.memprops.memory_heap_count as usize];
        let local: Vec<usize> = (0..self.memprops.memory_heap_count as usize)
            .filter(|&i| heaps[i].flags.contains(vk::MemoryHeapFlags::DEVICE_LOCAL))
            .collect();
        let total: u64 = local.iter().map(|&i| heaps[i].size).sum();
        if !self.budget {
            warn!("VK_EXT_memory_budget absent: reporting free = total ({total} B)");
            return (total as usize, total as usize);
        }
        let mut b = vk::PhysicalDeviceMemoryBudgetPropertiesEXT::default();
        let mut p2 = vk::PhysicalDeviceMemoryProperties2::default().push_next(&mut b);
        // SAFETY: `self.phys` is live; the chain outlives the call.
        unsafe {
            self.instance
                .get_physical_device_memory_properties2(self.phys, &mut p2)
        };
        let free: u64 = local
            .iter()
            .map(|&i| b.heap_budget[i].saturating_sub(b.heap_usage[i]))
            .sum();
        (free as usize, total as usize)
    }

    /// Device name, for startup logging and for test output.
    pub fn name(&self) -> String {
        // SAFETY: `self.phys` is live.
        let props = unsafe { self.instance.get_physical_device_properties(self.phys) };
        props.device_name_as_c_str().map_or_else(
            |_| "<unnamed>".to_string(),
            |s| s.to_string_lossy().into_owned(),
        )
    }
}

