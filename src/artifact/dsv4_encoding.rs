//! DeepSeek-V4's prompt encoding — a hand-port of `encoding/encoding_dsv4.py`, which ships
//! **inside the checkpoint** at `/var/db/rivoli/deepseek-v4-flash-0731/encoding/`.
//!
//! **This checkpoint has no `chat_template.jinja`, and that is deliberate.** Its README:
//!
//! > This release does not include a Jinja-format chat template. Instead, we provide a
//! > dedicated `encoding` folder with Python scripts and test cases demonstrating how to
//! > encode messages in OpenAI-compatible format into input strings for the model, and how
//! > to parse the model's text output.
//!
//! So there is nothing to load at runtime and no way to be *told* the framing is wrong. The
//! first V4 decode fed raw text to the model and got
//! `"The sky is blue because of Rayleigh scattering."` three times over — which is correct
//! **base-model** behaviour: outside an assistant turn the model is doing document
//! continuation and has no reason to emit `<｜end▁of▁sentence｜>`, so it ran to `-bench`.
//! EOS handling was never the bug.
//!
//! ## Why this file is gated on the reference's own vectors
//!
//! This repo has already been burned by exactly this. GLM's chat template lives only in the
//! fp8 SOURCE, `artifact::tokenizer::encode_chat_turns` hand-ports it, and that port sat on
//! GLM-4's `<|role|>\n` framing **for months** before anyone noticed — because a
//! wrongly-framed prompt still produces fluent text. A wrong port here is silent and
//! invalidates every downstream quality number.
//!
//! `tests/v4_encoding.rs` therefore gates this three ways, and the third exists because the
//! first two were demonstrably not enough:
//!
//! 1. the four gold files the checkpoint ships (`encoding/tests/test_output_{1,2,3,4}.txt`),
//!    byte-for-byte;
//! 2. the unit tests at the bottom of this file, whose expectations were **generated by
//!    running `encoding_dsv4.py`**, never by reading the README;
//! 3. `differential_against_the_reference`, which drives both implementations from one
//!    corpus and diffs the strings. Review on 2026-08-05 found a real divergence that 1 and
//!    2 both passed over — see `sort_tool_results_by_call_order`, which carries the account.
//!    The differential catches it in one run.
//!
//! Where the README and the code disagree the code wins; where this port and the reference
//! disagree, this port is wrong.
//!
//! **1 and 3 need the checkpoint on disk and skip (loudly) without it**, so on a machine
//! with no `/var/db/rivoli/deepseek-v4-flash-0731` only the hermetic unit tests run — which
//! is why a few of them deliberately re-cover ground the gold vectors already hold.
//!
//! ## Deliberate divergences, each with its reason
//!
//! - **`context` is not ported.** `encode_messages(context=…)` exists for prefix-caching a
//!   already-encoded conversation head. Nothing here caches prompts, and the parameter's
//!   interaction with `drop_thinking` (a second `_drop_thinking_messages` pass used only to
//!   recompute a slice offset) is the fiddliest code in the reference. Ported as
//!   `context = []`, which is what all four of the reference's own test cases pass.
//! - **A user turn's blocks are only the two kinds `merge_tool_messages` can produce.** The
//!   reference's `[Unsupported {type}]` fallback for a user `content_blocks` entry is dead:
//!   every path into `render_message` goes through `merge_tool_messages`, which *discards*
//!   any caller-supplied `content_blocks` and rebuilds them from `content`. (Confirmed by
//!   running it: a user message with an `image` block encodes to an empty user turn.) The
//!   same fallback inside a *tool result's* content list IS reachable, and is ported — in
//!   `tool_content`, at the boundary, since nothing downstream inspects the structure.
//! - **`direct_search_results`** appears in `_drop_thinking_messages`'s keep-list and in no
//!   other line of the reference; `render_message` would raise `NotImplementedError` on it.
//!   Not modelled.
//! - **The `role: "assistant"` key on the parser's return value** is a constant in the
//!   reference. Here it is the type of [`ParsedMessage`].
//! - **Null `content` renders as `""`, where the reference sometimes writes `None`.**
//!   `system` and `assistant` get a `content or ""` there and agree with this port —
//!   `assistant` matters, because `content: null` beside `tool_calls` is the ordinary OpenAI
//!   shape. `latest_reminder` and `tool` have no such guard, so a null formats Python's
//!   `None` straight into the prompt; that is a formatting slip, not a sequence the model was
//!   trained on. `user` is the third case and it RAISES there, so it raises here too.
//! - **Where the reference RAISES, this refuses too — at the BOUNDARY**, so the failure
//!   names the message index instead of surfacing halfway through a prompt: a non-string
//!   `content`, a null `content` on a `user` turn, an absent `function.arguments`, a `text`
//!   block whose `text` is null or not a string, a `tool` content block that is not an
//!   object, and a `task` — string or not — outside the six, on a message where the
//!   reference reaches its assert.
//!
//!   One case runs the other way and is recorded rather than fixed: a malformed `tool_calls`
//!   on a role that cannot render them (`system`, `latest_reminder`) is a `KeyError` there,
//!   because `tool_calls_from_openai_format` runs before the role dispatch, and is accepted
//!   here because only the assistant arm parses the key. No well-formed request reaches it.
//! - **OpenAI's array-of-parts `content` is ACCEPTED**, flattened through the reference's own
//!   `content_blocks` rule. It is standard in their schema and clients send it constantly.
//!   Precisely: on a `user` turn the reference raises TypeError, so there are no bytes and
//!   this fills a hole; on `system`/`developer`/`assistant` it emits a deterministic Python
//!   list repr and this **deliberately contradicts it**, because a list repr is not a
//!   sequence the model was trained on. The empty array agrees with the reference on those
//!   roles (`content or ""`). It is the one shape whose bytes the differential structurally
//!   cannot pin — see `text_content`.
//! - **It also refuses a list of things the reference RENDERS.** Each is a shape whose
//!   rendering is not worth guessing at, because the reference reaches it through Python's
//!   `str()`/`repr()` rather than through JSON — and, with array-of-parts now accepted, none
//!   of them is a shape a conforming OpenAI client emits. Enumerated because "it refuses
//!   more" is not a property anyone should have to rediscover:
//!
//!   | input | the reference renders | here |
//!   |---|---|---|
//!   | `content` a non-string, non-array scalar anywhere | `str()` of it | refused |
//!   | `content` falsy non-string, non-array (`0`, `false`) | `""`, via `content or ""` | refused |
//!   | `content` non-string on `latest_reminder` | `str()`/repr — no `or ""` guard at all | refused |
//!   | `content` a scalar or object on a `tool` turn | `str()`: `true`→`True`, `{}`→`{}` | refused |
//!   | a content block's `type` non-string | `[Unsupported {'a': 1}]`, Python's repr | refused |
//!   | `tools`/`tool_calls` falsy non-array (`{}`, `0`) | ignored | refused, but only on the role that parses the key |
//!   | a tool entry whose `function` is not an object | the scalar as a schema line | refused |
//!   | `function.name` non-string | `name="5"` | refused |
//!   | `function.name` null | `name="None"` — a call to a tool that does not exist | refused |
//!   | `task` invalid on a turn the assert never reaches | silently inert | refused |
//!   | `reasoning_content` falsy non-string (`0`, `[]`) | `""`, via `rc = … or ""` | refused |
//!   | `reasoning_content` truthy non-string | `str()`/repr of it, e.g. `<think>[1]</think>` | refused |
//!   | tool-call `id` / `tool_call_id` non-string | used as-is — they are live sort keys | refused |
//!   | `tools` on an `assistant`/`latest_reminder` turn | nothing, but drop_thinking flips | refused |
//!
//!   All measured against the reference 2026-08-06.
//! - **The rule that decides refuse-vs-reproduce, so the two are not per-case taste:**
//!   *Python's `None` is reproduced where it lands in CONTENT — text the model merely reads.
//!   It is refused where it lands in STRUCTURE, and everything that would go through
//!   `str()`/`repr()` is refused everywhere.*
//!
//!   Content, so reproduced: `<tool_result>None</tool_result>` (a null `tool` content),
//!   `<｜latest_reminder｜>None` (absent or null), `[Unsupported None]` (a block's absent or
//!   null `type`). `None` there is one determined four-character literal and the worst it
//!   does is put an odd word in the prompt — where refusing would 400 on the `tool` case,
//!   which is what an OpenAI client sends when a tool returns nothing.
//!
//!   Structure, so refused: a null `function.name` renders `name="None"` in the reference —
//!   a call to a tool that does not exist, which no client can dispatch. Reproducing it
//!   would hand the caller a broken tool call instead of an error. (An ABSENT `function.name`
//!   is a `KeyError` there and refused here too, so only the present-and-null case is a
//!   deliberate divergence.) Everything else is not determined anyway: `str(True)` is `True`
//!   and a dict interpolates as `{'a': 1}` with single quotes, so "reproduce the easy subset"
//!   would be a rule nobody could state.
//! - **`tools` on a `user` or `tool` turn is ACCEPTED and ignored**, matching the reference:
//!   `merge_tool_messages` rebuilds both dicts, so the key never reaches the `any(...)` scan.
//!   A round-1 version refused those too; review caught it as a disagreement in the *reject*
//!   direction, which is the one a strict port gets wrong most easily.
//!
//! ## The one behaviour that is NOT reproduced: Python's number formatting
//!
//! `python_json` matches `json.dumps`'s **separators** and its `ensure_ascii=False`, which is
//! what the tool-schema and `string="false"` bytes hinge on. It does not match Python's
//! **number repr**, and cannot without changing how the whole crate parses JSON. Measured
//! 2026-08-06, `json.dumps(json.loads(x))` against `serde_json`:
//!
//! | input | Python | this port | |
//! |---|---|---|---|
//! | `1e30`, `1e16` | `1e+30`, `1e+16` | `1e+30`, `1e+16` | agree |
//! | `1e-4`, `0.1`, `2.0` | `0.0001`, `0.1`, `2.0` | same | agree |
//! | `9007199254740993` | exact | exact | agree (`u64`, not `f64`) |
//! | `1e-5` | `1e-05` | `0.00001` | **differs** |
//! | `1e-7`, `2.5e-8` | `1e-07`, `2.5e-08` | `1e-7`, `2.5e-8` | **differs** |
//! | `1e-30` | `1e-30` | `9.999999999999999e-31` | **differs** (a parse ULP, not a format) |
//! | `123456789012345678901234567890` | exact digits | `1.2345678901234568e+29` | **differs** |
//!
//! So: Python switches to exponential below `1e-4` and zero-pads the exponent to two digits;
//! `ryu` does neither. Reachable from an ordinary JSON-Schema `minimum`/`multipleOf` of
//! `1e-5`, which would shift the bytes of the *system* prompt. The complete fix is
//! `serde_json/arbitrary_precision`, which preserves the literal — but that is a crate-wide
//! feature: it changes `Value::Number` for `format.rs`, `model.rs` and GLM's own
//! `tools_system_turn`, none of which are this track's to move. Recorded rather than
//! half-fixed, because a formatter that closed three of the four rows would look repaired
//! and still be wrong. `numeric_rendering_diverges_from_python` pins the table.
//!
//! Same root cause, same decision: `json.loads` accepts `NaN`/`Infinity` and `serde_json`
//! does not. So `arguments` of `{"x": NaN}` is decoded per-key there and takes the
//! unparseable-fallback branch here; and `arguments` of a bare `NaN` parses there and then
//! raises `AttributeError` on `.items()`, where here it renders as one `arguments`
//! parameter. The divergence runs in both directions and neither is reachable from a client
//! that emits standard JSON.

use crate::artifact::tokenizer::python_json;
use anyhow::{Result, bail, ensure};
use serde_json::Value;

